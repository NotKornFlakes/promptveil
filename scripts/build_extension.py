#!/usr/bin/env python3
"""Build the browser extension.

1. Copies the detection engine out of web/index.html into extension/engine.js
   (one source of truth for the web page and the extension).
2. Zips extension/ into dist/promptveil-extension-<version>.zip, ready to upload
   to the Chrome Web Store.

Usage: python3 scripts/build_extension.py
"""

import json
import re
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXT = ROOT / "extension"


def main() -> None:
    html = (ROOT / "web" / "index.html").read_text(encoding="utf-8")
    m = re.search(r'<script id="engine">(.*?)</script>', html, re.S)
    if not m:
        raise SystemExit("engine block not found in web/index.html")
    (EXT / "engine.js").write_text(
        "/* GENERATED by scripts/build_extension.py from web/index.html. Do not edit. */\n" + m.group(1).strip() + "\n",
        encoding="utf-8",
    )

    version = json.loads((EXT / "manifest.json").read_text())["version"]
    out = ROOT / "dist" / f"promptveil-extension-{version}.zip"
    out.parent.mkdir(exist_ok=True)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(EXT.rglob("*")):
            if f.is_file() and not f.name.startswith("."):
                z.write(f, f.relative_to(EXT))
    print(f"built {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
